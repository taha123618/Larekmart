import { ShipmentRepository } from "../repositories/shipment.repository.js";
import { ProviderRegistry } from "../providers/registry.js";
import { ShippingPublisher } from "../publishers/shipping.publisher.js";
import { ShipmentStatus } from "@repo/shipping-db";
import type {
  CreateShipmentRequest,
  Shipment,
  ShipmentStatus as TypeShipmentStatus,
} from "@repo/types";

export class ShipmentService {
  static async createShipment(
    request: CreateShipmentRequest,
  ): Promise<Shipment> {
    // Check if shipment already exists for this order
    const existing = await ShipmentRepository.findByOrderId(request.orderId);
    if (existing) {
      return this.formatShipment(existing);
    }

    // 1. Resolve carrier provider
    const provider = ProviderRegistry.getProvider(request.carrier);

    // 2. Request shipment creation from carrier provider
    let bookingResult;
    try {
      bookingResult = await provider.createShipment(request);
    } catch (err) {
      console.error(
        `[ShipmentService] Failed to book shipment with carrier '${request.carrier}':`,
        err,
      );
      // Fallback: create as PENDING without tracking number yet
      bookingResult = {
        carrier: request.carrier,
        trackingNumber: null,
        estimatedDeliveryAt: null,
      };
    }

    const initialStatus = bookingResult.trackingNumber
      ? ShipmentStatus.LABEL_CREATED
      : ShipmentStatus.PENDING;

    // 3. Persist shipment with address snapshot in PostgreSQL
    const isCod = Boolean(request.isCod);
    const codFee = bookingResult.codFee ?? request.codFee ?? 0;

    const shipment = await ShipmentRepository.createShipmentWithItems({
      ...request,
      isCod,
      codAmount: isCod ? (request.codAmount ?? 0) : null,
      codFee: isCod ? codFee : 0,
      trackingNumber: bookingResult.trackingNumber,
      status: initialStatus,
      estimatedDeliveryAt: bookingResult.estimatedDeliveryAt
        ? new Date(bookingResult.estimatedDeliveryAt)
        : null,
    });

    // 4. Record initial tracking event
    await ShipmentRepository.addTrackingEvent({
      shipmentId: shipment.id,
      status: initialStatus,
      description: bookingResult.trackingNumber
        ? `Shipment booking created with carrier ${shipment.carrier} (Tracking: ${bookingResult.trackingNumber})${isCod ? ` [COD Collection: PKR ${shipment.codAmount}]` : ""}`
        : `Shipment order created, pending carrier assignment`,
      source: "manual",
    });

    // 5. If label was automatically generated by carrier, save it
    if (bookingResult.labelUrl && bookingResult.trackingNumber) {
      await ShipmentRepository.addLabel({
        shipmentId: shipment.id,
        carrier: shipment.carrier,
        trackingNumber: bookingResult.trackingNumber,
        format: "pdf",
        labelUrl: bookingResult.labelUrl,
      });

      await ShippingPublisher.publishLabelCreated({
        shipmentId: shipment.id,
        orderId: shipment.orderId,
        trackingNumber: bookingResult.trackingNumber,
        carrier: shipment.carrier,
        labelUrl: bookingResult.labelUrl,
      });
    }

    // 6. Publish Kafka shipment.created event
    await ShippingPublisher.publishShipmentCreated({
      shipmentId: shipment.id,
      orderId: shipment.orderId,
      userId: shipment.userId,
      carrier: shipment.carrier,
      trackingNumber: shipment.trackingNumber,
      status: shipment.status as TypeShipmentStatus,
      shippingRateAmount: shipment.shippingRateAmount,
      currency: shipment.currency,
      isCod: shipment.isCod,
      codAmount: shipment.codAmount,
      codFee: shipment.codFee,
      codStatus: shipment.codStatus,
    });

    const refreshed = await ShipmentRepository.findById(shipment.id);
    return this.formatShipment(refreshed ?? shipment);
  }

  static async listShipments(params: {
    page?: number;
    limit?: number;
    carrier?: string;
    status?: string;
    search?: string;
    isCod?: boolean;
    codStatus?: string;
  } = {}) {
    const { shipments, pagination } = await ShipmentRepository.findAll({
      page: params.page,
      limit: params.limit,
      carrier: params.carrier,
      status: params.status as unknown as ShipmentStatus,
      search: params.search,
      isCod: params.isCod,
      codStatus: params.codStatus,
    });

    return {
      shipments: shipments.map((s) => this.formatShipment(s)),
      pagination,
    };
  }

  static async getShipmentById(id: string): Promise<Shipment> {
    const shipment = await ShipmentRepository.findById(id);
    if (!shipment) {
      throw new Error(`Shipment with id '${id}' not found`);
    }
    return this.formatShipment(shipment);
  }

  static async getShipmentByOrderId(orderId: string): Promise<Shipment | null> {
    const shipment = await ShipmentRepository.findByOrderId(orderId);
    if (!shipment) return null;
    return this.formatShipment(shipment);
  }

  static async cancelShipment(id: string, reason?: string): Promise<Shipment> {
    const shipment = await ShipmentRepository.findById(id);
    if (!shipment) {
      throw new Error(`Shipment with id '${id}' not found`);
    }

    if (
      shipment.status === ShipmentStatus.DELIVERED ||
      shipment.status === ShipmentStatus.CANCELLED
    ) {
      throw new Error(
        `Cannot cancel shipment with current status '${shipment.status}'`,
      );
    }

    // Cancel with provider if tracking number was booked
    if (shipment.trackingNumber) {
      try {
        const provider = ProviderRegistry.getProvider(shipment.carrier);
        await provider.cancelShipment({
          shipmentId: shipment.id,
          trackingNumber: shipment.trackingNumber,
          carrier: shipment.carrier,
          reason,
        });
      } catch (err) {
        console.warn(
          `[ShipmentService] Warning: Carrier cancel failed for shipment '${id}':`,
          err,
        );
      }
    }

    // Update status to CANCELLED in DB
    const updated = await ShipmentRepository.updateStatus(
      shipment.id,
      ShipmentStatus.CANCELLED,
    );

    // Record tracking event
    await ShipmentRepository.addTrackingEvent({
      shipmentId: shipment.id,
      status: ShipmentStatus.CANCELLED,
      description: `Shipment cancelled: ${reason ?? "User or order cancellation"}`,
      source: "manual",
    });

    // Publish Kafka shipment.cancelled
    await ShippingPublisher.publishCancelled({
      shipmentId: shipment.id,
      orderId: shipment.orderId,
      reason,
    });

    return this.formatShipment(updated);
  }

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  private static formatShipment(shipment: any): Shipment {
    return {
      id: shipment.id,
      orderId: shipment.orderId,
      userId: shipment.userId,
      carrier: shipment.carrier,
      serviceType: shipment.serviceType,
      trackingNumber: shipment.trackingNumber,
      status: shipment.status as TypeShipmentStatus,
      shippingAddress: shipment.shippingAddress,
      shippingRateAmount: shipment.shippingRateAmount,
      currency: shipment.currency,
      isCod: shipment.isCod ?? false,
      codAmount: shipment.codAmount ?? null,
      codFee: shipment.codFee ?? null,
      codStatus: shipment.codStatus ?? null,
      estimatedDeliveryAt: shipment.estimatedDeliveryAt?.toISOString() ?? null,
      shippedAt: shipment.shippedAt?.toISOString() ?? null,
      deliveredAt: shipment.deliveredAt?.toISOString() ?? null,
      items:
        shipment.items?.map((item: any) => ({
          id: item.id,
          shipmentId: item.shipmentId,
          productId: item.productId,
          name: item.name,
          quantity: item.quantity,
          price: item.price,
          weight: item.weight,
          sku: item.sku,
        })) ?? [],
      packages:
        shipment.packages?.map((pkg: any) => ({
          id: pkg.id,
          shipmentId: pkg.shipmentId,
          weight: pkg.weight,
          length: pkg.length,
          width: pkg.width,
          height: pkg.height,
          packageType: pkg.packageType,
        })) ?? [],
      labels:
        shipment.labels?.map((label: any) => ({
          id: label.id,
          shipmentId: label.shipmentId,
          carrier: label.carrier,
          trackingNumber: label.trackingNumber,
          format: label.format,
          labelUrl: label.labelUrl,
          cost: label.cost,
          createdAt: label.createdAt.toISOString(),
        })) ?? [],
      metadata: shipment.metadata,
      createdAt: shipment.createdAt.toISOString(),
      updatedAt: shipment.updatedAt.toISOString(),
    };
  }
}
